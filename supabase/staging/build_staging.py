"""Generate supabase/staging/staging_schema.sql.

Builds a "staging" copy of the app's database inside the SAME Supabase
project, from:
  1. a schema-only pg_dump of production (public schema), which captures
     tables, policies and triggers that were created outside the
     migrations folder, and
  2. the migrations not yet applied to production (security hotfix,
     reporting, blocking, admin dashboard),
with every public.* reference rewritten to staging.* and app_private.* to
staging_private.*.

usage: python supabase/staging/build_staging.py <prod_schema_dump.sql>

The output is checked so it can never touch production objects: no
public.* names, no writes to auth/storage, no triggers on auth tables.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIGRATIONS = HERE.parent / 'migrations'
OUT = HERE / 'staging_schema.sql'

PENDING_MIGRATIONS = [
    '20261120000000_security_hotfix.sql',
    '20261121000500_reports_moderation.sql',
    '20261121000600_user_blocks.sql',
    '20261121000700_admin_dashboard.sql',
]

# Production objects deliberately not copied.
SKIP_FUNCTIONS = {
    'handle_new_user',        # fires from auth.users; staging profiles are seeded instead
    'get_email_by_username',  # replaced by email login
}
SKIP_TABLE_PREFIX = '_backup_'
KEEP_TYPES = {'TABLE', 'CONSTRAINT', 'FK CONSTRAINT', 'INDEX', 'FUNCTION',
              'POLICY', 'ROW SECURITY', 'TRIGGER', 'ACL'}

HEADER_RE = re.compile(r'^--\n-- Name: (?P<name>.*?); Type: (?P<type>.*?); Schema: (?P<schema>.*?); Owner: .*?\n--\n',
                       re.M)


def dump_blocks(text):
    heads = list(HEADER_RE.finditer(text))
    for i, h in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        body = text[h.end():end]
        body = re.sub(r'^\\(un)?restrict .*$', '', body, flags=re.M)
        yield h['name'], h['type'], h['schema'], body.strip()


def keep(name, typ, schema):
    if schema != 'public' or typ not in KEEP_TYPES:
        return False
    if SKIP_TABLE_PREFIX in name:
        return False
    if typ == 'ACL' and name == 'SCHEMA public':
        return False
    fn = re.match(r'(?:FUNCTION )?(\w+)\(', name)
    if typ in ('FUNCTION', 'ACL') and fn and fn.group(1) in SKIP_FUNCTIONS:
        return False
    return True


def to_staging(sql):
    sql = re.sub(r'\bapp_private\b', 'staging_private', sql)
    sql = re.sub(r'\bpublic\.', 'staging.', sql)
    sql = sql.replace("'public'", "'staging'")
    sql = re.sub(r'search_path = public\b', 'search_path = staging', sql)
    sql = re.sub(r'IN SCHEMA public\b', 'IN SCHEMA staging', sql)
    return sql


PRELUDE = """\
-- =============================================================
-- GENERATED by supabase/staging/build_staging.py. Do not edit by hand.
--
-- Staging copy of the School Board database in its own schemas
-- (staging, staging_private) inside the production Supabase project.
-- Production tables, data, policies and functions are not touched.
-- Shared with production (schema isolation does NOT isolate these):
-- Auth users, Storage buckets, Realtime, API settings, rate limits.
--
-- Contents: production public schema as of the 2026-11-22 dump
-- (minus image backups, handle_new_user, get_email_by_username), then
-- the security hotfix and the 20261121000500-000700 migrations, then
-- a gate so only seeded staging test accounts can use staging.
-- Remove with supabase/staging/staging_teardown.sql.
-- =============================================================

SET client_encoding = 'UTF8';
BEGIN;

CREATE SCHEMA staging;
CREATE SCHEMA staging_private;
REVOKE ALL ON SCHEMA staging_private FROM PUBLIC;
GRANT USAGE ON SCHEMA staging TO anon, authenticated, service_role;
GRANT USAGE ON SCHEMA staging_private TO authenticated;

SET LOCAL search_path = staging, pg_catalog;
SET LOCAL check_function_bodies = false;
"""

GATE = """
-- =============================================================
-- Gate: staging is for seeded test accounts only.
-- The API exposes staging to every signed-in production user, so every
-- staging table gets a RESTRICTIVE policy: you must have a
-- staging.profiles row, and only SQL (staging_seed.sql) creates those.
-- =============================================================
CREATE FUNCTION staging_private.is_staging_member()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = staging
AS $$
  SELECT EXISTS (SELECT 1 FROM staging.profiles WHERE id = (SELECT auth.uid()));
$$;
REVOKE ALL ON FUNCTION staging_private.is_staging_member() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION staging_private.is_staging_member() TO authenticated;

-- No self-enrolment: drop every client INSERT policy on staging.profiles.
DO $$
DECLARE p record;
BEGIN
  FOR p IN SELECT policyname FROM pg_policies
           WHERE schemaname = 'staging' AND tablename = 'profiles' AND cmd = 'INSERT' LOOP
    EXECUTE format('DROP POLICY %I ON staging.profiles', p.policyname);
  END LOOP;
END $$;

DO $$
DECLARE t record;
BEGIN
  FOR t IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
           WHERE n.nspname = 'staging' AND c.relkind = 'r' LOOP
    EXECUTE format('ALTER TABLE staging.%I ENABLE ROW LEVEL SECURITY', t.relname);
    EXECUTE format(
      'CREATE POLICY "Staging: test accounts only" ON staging.%I AS RESTRICTIVE FOR ALL
         TO authenticated USING ((SELECT staging_private.is_staging_member()))
         WITH CHECK ((SELECT staging_private.is_staging_member()))', t.relname);
  END LOOP;
END $$;

-- anon never needs staging tables (the hotfix copy already revoked them;
-- repeated here so the gate holds even if that changes).
REVOKE ALL ON ALL TABLES IN SCHEMA staging FROM anon;

COMMIT;

-- Optional, separate step (shared Realtime publication; needs approval):
--   ALTER PUBLICATION supabase_realtime ADD TABLE staging.messages;
"""

FORBIDDEN = [
    (re.compile(r'\bpublic\.'), 'reference to a production public.* object'),
    (re.compile(r'\bapp_private\b'), 'reference to production app_private'),
    (re.compile(r'(INSERT INTO|UPDATE|DELETE FROM|ALTER TABLE|TRUNCATE)\s+(auth|storage)\.', re.I),
     'write to shared auth/storage'),
    (re.compile(r'CREATE\s+(OR REPLACE\s+)?TRIGGER[^;]*\bON\s+(auth|storage)\.', re.I | re.S),
     'trigger on shared auth/storage'),
    (re.compile(r'storage\.(objects|buckets)', re.I), 'storage policy or bucket'),
    (re.compile(r'ALTER PUBLICATION(?![^\n]*--)', re.I), 'realtime publication change (keep it a manual step)'),
]


def strip_comments(sql):
    return '\n'.join(line for line in sql.splitlines() if not line.lstrip().startswith('--'))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    dump = Path(sys.argv[1]).read_text(encoding='utf-8')

    parts = [PRELUDE, '\n-- ---------- production public schema (2026-11-22 dump) ----------\n']
    kept = 0
    for name, typ, schema, body in dump_blocks(dump):
        if keep(name, typ, schema):
            parts.append(f'\n-- {typ}: {name}\n{to_staging(body)}\n')
            kept += 1

    for m in PENDING_MIGRATIONS:
        text = (MIGRATIONS / m).read_text(encoding='utf-8')
        parts.append(f'\n-- ---------- {m} ----------\n{to_staging(text)}\n')
    parts.append(GATE)
    out = ''.join(parts)

    code = strip_comments(out)
    problems = [why for rx, why in FORBIDDEN if rx.search(code)]
    if problems:
        sys.exit('refusing to write staging SQL: ' + '; '.join(sorted(set(problems))))

    OUT.write_text(out, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(HERE.parent.parent)}: {kept} production objects + {len(PENDING_MIGRATIONS)} migrations')


if __name__ == '__main__':
    main()
